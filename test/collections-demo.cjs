const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const ts=require('typescript');
const {randomUUID}=require('node:crypto');
const code=ts.transpileModule(fs.readFileSync(path.join(__dirname,'../src/services/collections.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const storage=new Map();
const localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)};
const fakeApi={isDemo:true,demoIdentity:{id:'demo-user'},client:null};
const mod={exports:{}};
vm.runInNewContext(`(function(require,module,exports,localStorage,crypto){${code}\n})`)((name)=>{
  if(name==='./api')return fakeApi;
  throw new Error(`Unexpected import: ${name}`);
},mod,mod.exports,localStorage,{randomUUID});
const api=mod.exports;
(async()=>{
  assert.equal((await api.loadCollections()).collections.length,0);
  const id=await api.createCollection('My workflow','Sample collection',null);
  let index=await api.loadCollections();
  assert.equal(index.collections[0].name,'My workflow');
  assert.equal(index.collections[0].owner_user_id,'demo-user');
  await api.updateCollection(id,'Updated workflow','Revised');
  await api.addCollectionItem(id,'p1');
  await api.addCollectionItem(id,'p2');
  await api.addCollectionItem(id,'p1');
  index=await api.loadCollections();
  assert.equal(index.collections[0].name,'Updated workflow');
  assert.equal(index.items.length,2,'Same prompt must not be duplicated');
  await api.moveCollectionItem(id,'p2','up');
  index=await api.loadCollections();
  const order=[...index.items].sort((a,b)=>a.sort_order-b.sort_order).map(x=>x.prompt_id);
  assert.equal(order.join(','),'p2,p1');
  await api.removeCollectionItem(id,'p1');
  assert.equal((await api.loadCollections()).items.length,1);
  await api.deleteCollection(id);
  assert.equal((await api.loadCollections()).collections.length,0);
  assert.equal((await api.loadCollections()).items.length,0);
  console.log('PASS: demo collection creation, edit, item dedup, ordering, removal and deletion');
})().catch(error=>{console.error(error);process.exitCode=1});
