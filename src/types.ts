export type View = 'explore' | 'mine' | 'teams' | 'reviews' | 'notifications' | 'admin';
export type Filter = 'All prompts' | 'Personal' | 'My teams' | 'Other teams' | 'Favorites';
export type Lifecycle = 'draft' | 'published' | 'archived';
export type Approval = 'experimental' | 'under_review' | 'approved' | 'deprecated';
export type PromptBody = {
  title: string;
  description: string;
  content: string;
  category: string;
  tags: string[];
  usage_instructions: string;
  example_inputs: string;
  expected_outputs: string;
  compatible_models: string[];
};
export type Prompt = {
  id: string;
  owner_user_id: string | null;
  owner_team_id: string | null;
  created_by: string;
  lifecycle: Lifecycle;
  official_version_id: string | null;
  latest_version_id: string | null;
  source_prompt_id?: string | null;
  created_at: string;
  updated_at: string;
  deleted_at: string | null;
};
export type PromptVersion = PromptBody & {
  id: string;
  prompt_id: string;
  version_number: number;
  approval_status: Approval;
  decision: string;
  decision_reason: string;
  change_note: string;
  author_id: string;
  created_at: string;
};
export type Team = { id: string; name: string; description: string; created_at?: string };
export type Member = { team_id: string; user_id: string; role: 'member' | 'manager' };
export type Profile = { id: string; display_name: string; email: string };
export type Favorite = { user_id: string; prompt_id: string };
export type Proposal = {
  id: string;
  prompt_id: string;
  author_id: string;
  proposed_content: PromptBody;
  rationale: string;
  status: 'open' | 'under_review' | 'accepted' | 'rejected';
  created_at: string;
  decision_reason?: string;
};
// export type Notice = { id: string; recipient_id: string; message: string; read_at: string | null; created_at: string };
export type Notice = {
  id: string;
  recipient_id: string;
  message: string;
  prompt_id: string | null;
  read_at: string | null;
  created_at: string;
};
export type Audit = { id: number; actor_id: string; team_id: string | null; prompt_id: string | null; event_type: string; description: string; created_at: string };
export type AppData = {
  prompts: Prompt[];
  versions: PromptVersion[];
  teams: Team[];
  members: Member[];
  profiles: Profile[];
  favorites: Favorite[];
  proposals: Proposal[];
  notifications: Notice[];
  admins: {user_id: string}[];
  audit: Audit[];
  categories: {name:string}[];
  recommendations: {prompt_id:string;team_id:string;recommended_by:string}[];
  settings: {id:boolean;retention_days:number;temporary_password_hours:number}[];
  account_controls: {user_id:string;disabled:boolean;must_change_password:boolean;temporary_password_expires_at:string|null}[];
};
export type Identity = { id: string; email: string };
export type ReviewItem = {kind: 'version' | 'proposal'; prompt: Prompt; record: PromptVersion | Proposal};
export const emptyData = (): AppData => ({prompts: [], versions: [], teams: [], members: [], profiles: [], favorites: [], proposals: [], notifications: [], admins: [], audit: [], categories: [], recommendations: [], settings: [], account_controls: []});
export const blankBody = (): PromptBody => ({title: '', description: '', content: '', category: 'Writing', tags: [], usage_instructions:'', example_inputs:'', expected_outputs:'', compatible_models:[]});
